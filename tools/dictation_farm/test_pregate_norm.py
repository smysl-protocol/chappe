# -*- coding: utf-8 -*-
"""Замки нормализации лексического пре-гейта (решение владельца 03.08).

Разбор docs/reports/pregate_analysis_2026-08-03.md: 88% лексических
отказов синтетического стресса — ASR-опечатки СЛОВАРНЫХ слов («мсот»,
«вдоа», «жжжди»). Токен, не прошедший лексикон с первого раза,
нормализуется ДО подсчёта доли «вне лексикона»:
  1) повторы букв (3 и более одинаковых подряд → одна),
     лексикон пробуется снова;
  2) если не помогло — расстояние Дамерау-Левенштейна 1 до слова
     лексикона; токены длиной <=3 расстоянием НЕ лечатся (ложные
     срабатывания на предлогах).
Токен, прошедший нормализацию, считается В лексиконе.

ЦИФРОВОЕ правило (>15% цифр) НЕ ТРОНУТО — решение владельца, ждёт
полевого корпуса. Стоп-лист филлеров НЕ добавлен (отдельная мера,
владелец её не заказывал).

Зеркало Swift — ChappeTests/PreGateNormalizationTests (расхождение
логики зеркал = баг).
Запуск: python3 tools/dictation_farm/test_pregate_norm.py (0 = замки целы)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "semdict"))

import farm_text as FT  # noqa: E402


def check(cond, label):
    if not cond:
        print(f"ЗАМОК СЛОМАН: {label}")
    return bool(cond)


def main():
    ok = True

    # --- схлопывание повторов: 3+ одинаковых подряд -> одна ---
    ok &= check(FT.collapse_repeats("жжжди") == "жди",
                "«жжжди» не схлопнулось в «жди»")
    ok &= check(FT.collapse_repeats("утррро") == "утро",
                "«утррро» не схлопнулось в «утро»")
    ok &= check(FT.collapse_repeats("рынооооок") == "рынок",
                "«рынооооок» не схлопнулось в «рынок»")
    # двойная буква — законная орфография, не трогаем
    ok &= check(FT.collapse_repeats("аллея") == "аллея",
                "двойная буква не должна схлопываться")
    ok &= check(FT.collapse_repeats("мост") == "мост",
                "слово без повторов не должно меняться")

    # --- расстояние 1: перестановка, замена, пропуск, вставка ---
    ok &= check(FT.normalized_in_lexicon("мсот"), "«мсот» -> «мост»")
    ok &= check(FT.normalized_in_lexicon("вдоа"), "«вдоа» -> «вода»")
    ok &= check(FT.normalized_in_lexicon("ырнок"), "«ырнок» -> «рынок»")
    ok &= check(FT.normalized_in_lexicon("лодак"), "«лодак» -> «лодка»")
    # глубокое искажение (расстояние >=2) — не лечится, честный отказ
    ok &= check(not FT.normalized_in_lexicon("еербг"),
                "глубокое искажение «еербг» не должно лечиться")

    # --- токены <=3 букв: расстояние не применяется ---
    # «мст» в одной правке от «мост», но короткие токены дают ложные
    # совпадения с предлогами — расстояние выключено
    ok &= check(not FT.normalized_in_lexicon("мст"),
                "токен <=3 не должен лечиться расстоянием")

    # --- сообщение из одних опечаток словарных слов проходит пре-гейт ---
    ok &= check(FT.pre_detect("мсот вдоа жжжди") is None,
                "«мсот вдоа жжжди» обязано проходить пре-гейт")
    # 4 содержательных слова — работает порог, а не guard «<4 слов»;
    # без нормализации было бы 100% вне лексикона -> отказ
    ok &= check(FT.pre_detect("мсот вдоа ырнок утррро") is None,
                "«мсот вдоа ырнок утррро» обязано проходить пре-гейт")

    # --- честный отказ остаётся отказом: URL не лечится ---
    ok &= check(FT.pre_detect("https://example.com/x?y=1#z жди")
                == "прегейт: вне лексикона >37%",
                "URL обязан по-прежнему уходить текстом")

    # --- ЗАМОК: цифровое правило не задето (решение владельца) ---
    # «встретимся в 12:05» по-прежнему режется — текущее поведение
    # (отчёт 03.08); менять его можно только по полевому корпусу
    ok &= check(FT.pre_detect("встретимся в 12:05")
                == "прегейт: много цифр",
                "цифровое правило изменилось — это запрещено")

    print("замки нормализации пре-гейта:", "целы" if ok else "СЛОМАНЫ")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
