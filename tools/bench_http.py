скорости = []          # ток/с всех коротких запросов (для среднего)
результаты = []        # итоговые строки отчёта


def записать(имя, итог, детали, скорость=None):
    результаты.append({"тест": имя, "итог": итог, "детали": детали,
                       "tok_s": round(скорость, 1) if скорость else None})
    print(f"\n=== {имя} ===")
    print(f"  итог: {итог}")
    for строка in детали.split("\n"):
        print(f"  {строка}")
    if скорость:
        print(f"  скорость: {скорость:.1f} tok/s")


def тест_1_русский_диалог():
    текст, ток_с, err = chat(
        "Ответь по-русски, в двух-трёх предложениях: как правильно хранить "
        "запас питьевой воды в жарком влажном климате?")
    if err:
        записать("1. Русский диалог", "ОШИБКА", err)
        return
    скорости.append(ток_с)
    доли, _ = доли_письменностей(текст)
    чисто = (доли["кириллица"] >= 0.90 and доли["арабская"] == 0
             and доли["иероглифы"] == 0)
    итог = "чисто" if чисто else "ЕСТЬ УТЕЧКА других письменностей"
    записать("1. Русский диалог", итог,
             f"кириллица {доли['кириллица']:.0%}, латиница {доли['латиница']:.0%}, "
             f"арабская {доли['арабская']:.0%}, иероглифы {доли['иероглифы']:.0%}\n"
             f"ответ: {текст[:200]}", ток_с)


ФРАЗА = "Тропа размыта после ливня, идём в обход через хребет, вернёмся к закату."


def тест_перевода(номер, язык, инструкция, проверка_слов, ожидаемая_письменность):
    текст, ток_с, err = chat(f"{инструкция} Ответь только переводом, без пояснений.\n"
                             f"«{ФРАЗА}»")
    if err:
        записать(f"{номер}. Перевод {язык}", "ОШИБКА", err)
        return
    скорости.append(ток_с)
    доли, _ = доли_письменностей(текст)
    письменность_ок = доли[ожидаемая_письменность] >= 0.80
    слова_ок = any(с in текст.lower() for с in проверка_слов)
    if письменность_ок and слова_ок:
        итог = "перевод похож на правду"
    elif письменность_ок:
        итог = "письменность верная, но слова-маркеры не найдены — проверь глазами"
    else:
        итог = "НЕ ТА письменность в ответе"
    записать(f"{номер}. Перевод {язык}", итог,
             f"{ожидаемая_письменность} {доли[ожидаемая_письменность]:.0%}, "
             f"кириллица {доли['кириллица']:.0%}\nответ: {текст[:200]}", ток_с)


def тест_5_сжатие():
    ЛИМИТ = 120   # символов; проверяет код, не модель (правило проекта)
    длинное = ("Мы на северном пляже за третьим пирсом, у моего друга сильно "
               "порезана нога, кровь не останавливается уже минут двадцать, нас "
               "тут трое, аптечки нет, телефон почти сел, нужен кто-то с бинтами "
               "и лодка чтобы вывезти нас отсюда как можно быстрее.")
    текст, ток_с, err = chat(
        f"Сожми сообщение до самого главного, не длиннее {ЛИМИТ} символов. "
        f"Сохрани: что случилось, сколько людей, что нужно. Ответь только "
        f"сжатым текстом.\n\n{длинное}")
    if err:
        записать("5. Сжатие сообщения", "ОШИБКА", err)
        return
    скорости.append(ток_с)
    факт = len(текст)
    ключи = {"кровотечение/кровь": "кров" in текст.lower(),
             "лодка": "лодк" in текст.lower(),
             "трое/3": ("трое" in текст.lower() or "3" in текст)}
    смысл = sum(ключи.values())
    # Модель НЕ умеет считать символы — потому и проверяем кодом.
    # Небольшой перебор (до 1.5 лимита) терпим: в приложении дожмёт код.
    длина_ок = факт <= ЛИМИТ * 1.5
    итог = (f"{факт} симв. (лимит {ЛИМИТ}), смысл {смысл}/3"
            + ("" if длина_ок and смысл >= 2 else " — СЛАБО"))
    записать("5. Сжатие сообщения", итог,
             f"ключи: {ключи}\nответ: {текст}", ток_с)


# --- Тест 6: SOS -> JSON по жёсткой схеме (как в test_schema2.py) ---

SOS_MSG = ("Мы на северном пляже за третьим пирсом, у моего друга сильно порезана нога, "
           "кровь не останавливается уже минут двадцать, нас тут трое, аптечки нет, "
           "телефон почти сел, нужен кто-то с бинтами и лодка чтобы вывезти.")

SOS_SCHEMA = {
    "type": "object",
    "properties": {
        "type":         {"type": "string", "enum": ["sos", "medical", "info"]},
        "severity":     {"type": "string", "enum": ["low", "medium", "high", "critical"]},
        "people_count": {"type": "integer", "minimum": 0, "maximum": 31},
        "injury":       {"type": "string", "enum": ["none", "bleeding", "fracture",
                                                    "burn", "head", "unconscious", "other"]},
        "needs": {
            "type": "array",
            "minItems": 1,
            "maxItems": 4,                      # потолок против зацикливания
            "items": {"type": "string",
                      "enum": ["bandages", "water", "food", "boat", "vehicle",
                               "doctor", "medicine", "evacuation", "fuel", "shelter"]}
        }
    },
    "required": ["type", "severity", "people_count", "injury", "needs"],
    "additionalProperties": False
}

# С 25.07.2026 промпт перечисляет допустимые значения ВСЕХ enum-полей
# (правило №8 CLAUDE.md): без списка модель тянется к слову вне enum,
# и грамматика захватывает ложный префикс («head» вместо «bleeding»;
# позже «shelter» вместо «bandages» на телефоне — needs не были перечислены).
# Эталон Bonsai Q1_0 гонялся ещё старым промптом — учитывать при сравнении.
SOS_PROMPT = (
    "Ты обрабатываешь сигнал бедствия. Извлеки факты из сообщения и заполни поля.\n"
    "Правила: type — одно из: sos, medical, info (sos = нужна срочная помощь). "
    "severity — одно из: low, medium, high, critical (critical = угроза жизни). "
    "injury — главная травма, строго одно из значений: none, bleeding, fracture, "
    "burn, head, unconscious, other (head = травма головы). "
    "needs — только то, что прямо просят, каждый пункт строго из списка: bandages, "
    "water, food, boat, vehicle, doctor, medicine, evacuation, fuel, shelter.\n\n"
    "Сообщение: " + SOS_MSG + "\n\nОтвет:"
)

SOS_ЭТАЛОН = {"type": "sos", "severity": "critical", "people_count": 3,
              "injury": "bleeding"}
SOS_NEEDS = {"bandages", "boat"}


def тест_6_sos_json(прогонов=3):
    """Главный тест. Схема подаётся через json_schema на /completion —
    ровно тот путь, что работал в test_schema2.py."""
    очки, разборы = [], []
    for i in range(прогонов):
        # temp 0 + top_k 1 (жадный выбор) — как в приложении: извлечение
        # фактов детерминировано, без лотереи сэмплинга (правило №8).
        resp, err = _post("/completion", {
            "prompt": SOS_PROMPT,
            "n_predict": 200,
            "temperature": 0.0,
            "top_k": 1,
            "json_schema": SOS_SCHEMA,
        })
        if err:
            разборы.append(f"прогон {i+1}: ОШИБКА {err}")
            continue
        raw = resp.get("content", "")
        try:
            obj = json.loads(raw)
        except json.JSONDecodeError:
            разборы.append(f"прогон {i+1}: не разобрался JSON: {raw[:120]}")
            очки.append(0)
            continue
        балл = sum(obj.get(k) == v for k, v in SOS_ЭТАЛОН.items())
        балл += SOS_NEEDS.issubset(set(obj.get("needs", [])))
        очки.append(балл)
        разборы.append(f"прогон {i+1}: {балл}/5 · {json.dumps(obj, ensure_ascii=False)}")

    if очки:
        итог = f"{'/'.join(str(о) for о in очки)} из 5 за прогон"
        if min(очки) == 5:
            итог += " — идеально"
        elif max(очки) < 4:
            итог += " — ПЛОХО"
    else:
        итог = "ОШИБКА: все прогоны упали"
    записать("6. SOS -> JSON (схема)", итог, "\n".join(разборы))
    return очки


def тест_6б_не_sos(прогонов=3):
    """Негативный контроль из tests/sos_extraction_vectors.json:
    рассказ про поход с «тревожными» словами (кровь, нога, трое), но без
    бедствия. Любая модель обязана дать type != sos и severity != critical —
    защита от регресса при смене модели (правило №9 CLAUDE.md)."""
    векторы = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                           "tests", "sos_extraction_vectors.json")
    with open(векторы, encoding="utf-8") as f:
        данные = json.load(f)
    случай = next(c for c in данные["cases"] if c["name"] == "не_sos_поход")
    промпт = (
        "Ты обрабатываешь сигнал бедствия. Извлеки факты из сообщения и заполни поля.\n"
        "Правила: type — одно из: sos, medical, info (sos = нужна срочная помощь). "
        "severity — одно из: low, medium, high, critical (critical = угроза жизни). "
        "injury — главная травма, строго одно из значений: none, bleeding, fracture, "
        "burn, head, unconscious, other (head = травма головы). "
        "needs — только то, что прямо просят, каждый пункт строго из списка: bandages, "
        "water, food, boat, vehicle, doctor, medicine, evacuation, fuel, shelter.\n\n"
        "Сообщение: " + случай["message"] + "\n\nОтвет:")
    исходы, разборы = [], []
    for i in range(прогонов):
        resp, err = _post("/completion", {
            "prompt": промпт, "n_predict": 200,
            "temperature": 0.0, "top_k": 1,
            "json_schema": данные["schema"],
        })
        if err:
            разборы.append(f"прогон {i+1}: ОШИБКА {err}")
            continue
        try:
            obj = json.loads(resp.get("content", ""))
        except json.JSONDecodeError:
            разборы.append(f"прогон {i+1}: не разобрался JSON")
            исходы.append(False)
            continue
        ок = obj.get("type") != "sos" and obj.get("severity") != "critical"
        исходы.append(ок)
        разборы.append(f"прогон {i+1}: {'не-SOS' if ок else 'ЛОЖНЫЙ SOS'} · "
                       + json.dumps(obj, ensure_ascii=False))
    if исходы and all(исходы):
        итог = f"{len(исходы)}/{len(исходы)} — ложных SOS нет"
    elif исходы:
        итог = f"{sum(исходы)}/{len(исходы)} — ЕСТЬ ЛОЖНЫЕ SOS, регресс!"
    else:
        итог = "ОШИБКА: все прогоны упали"
    записать("6б. Не-SOS контроль (поход)", итог, "\n".join(разборы))
    return исходы


def тест_7_первая_помощь():
    """Длинная генерация: качество инструкции + tok/s + деградация."""
    текст, ток_с_длинный, err = chat(
        "Дай подробную пошаговую инструкцию первой помощи при сильном "
        "кровотечении из ноги. По-русски, пронумерованными шагами.",
        max_tokens=600)
    if err:
        записать("7. Инструкция первой помощи", "ОШИБКА", err)
        return None
    доли, букв = доли_письменностей(текст)
    признаки = {"давление на рану": "давлен" in текст.lower(),
                "жгут": "жгут" in текст.lower(),
                "нумерация шагов": "1." in текст or "1)" in текст,
                "объём (>400 симв.)": len(текст) > 400,
                "чистый русский": доли["кириллица"] >= 0.9}
    балл = sum(признаки.values())
    записать("7. Инструкция первой помощи", f"{балл}/5 признаков",
             f"{признаки}\nдлина {len(текст)} симв.\nначало: {текст[:200]}",
             ток_с_длинный)
    return ток_с_длинный


