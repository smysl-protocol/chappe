# Сэмплинг — тот же, что в run_llama.sh для 8B (чтобы сравнение было честным)
SAMPLING = {"temperature": 0.5, "top_p": 0.85, "top_k": 20, "min_p": 0}

# ---------------------------------------------------------------------------
# HTTP-помощники
# ---------------------------------------------------------------------------


def _post(path, payload, timeout=300):
    """POST с JSON. Возвращает (ответ, ошибка)."""
    req = urllib.request.Request(BASE + path,
                                 data=json.dumps(payload).encode(),
                                 headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return json.loads(r.read().decode()), None
    except urllib.error.HTTPError as e:
        return None, f"HTTP {e.code}: {e.read().decode()[:400]}"
    except Exception as e:
        return None, f"{type(e).__name__}: {e}"


def chat(prompt, max_tokens=200):
    """Обычный запрос через /v1/chat/completions.

    Возвращает (текст, ток/с, ошибка). Скорость берём из поля timings
    сервера — это скорость именно генерации, без обработки промпта.
    """
    payload = {"messages": [{"role": "user", "content": prompt}],
               "max_tokens": max_tokens, **SAMPLING}
    t0 = time.time()
    resp, err = _post("/v1/chat/completions", payload)
    wall = time.time() - t0
    if err:
        return None, 0.0, err

    text = resp["choices"][0]["message"]["content"].strip()

    # Скорость: сервер сам сообщает ток/с; если нет — считаем по часам
    tok_s = 0.0
    timings = resp.get("timings") or {}
    if timings.get("predicted_per_second"):
        tok_s = timings["predicted_per_second"]
    else:
        n = (resp.get("usage") or {}).get("completion_tokens", 0)
        tok_s = n / wall if wall > 0 else 0.0
    return text, tok_s, None


# ---------------------------------------------------------------------------
# Определение письменности (для проверки утечки языков)
# ---------------------------------------------------------------------------


def доли_письменностей(text):
    """Считает, сколько букв каждой письменности в тексте.

    Возвращает словарь долей от общего числа букв (пробелы, цифры
    и знаки препинания не считаются).
    """
    счёт = {"кириллица": 0, "латиница": 0, "арабская": 0, "иероглифы": 0, "другое": 0}
    for ch in text:
        if not ch.isalpha():
            continue
        o = ord(ch)
        if 0x0400 <= o <= 0x052F:
            счёт["кириллица"] += 1
        elif (0x0041 <= o <= 0x007A) or (0x00C0 <= o <= 0x024F):
            счёт["латиница"] += 1
        elif (0x0600 <= o <= 0x077F) or (0xFB50 <= o <= 0xFEFF):
            счёт["арабская"] += 1
        elif (0x4E00 <= o <= 0x9FFF) or (0x3040 <= o <= 0x30FF) or (0xAC00 <= o <= 0xD7AF):
            счёт["иероглифы"] += 1
        else:
            счёт["другое"] += 1
    всего = sum(счёт.values()) or 1
    return {k: v / всего for k, v in счёт.items()}, всего


