import Foundation

// ============================================================================
// WP1 (05.08.2026, вторая сессия): пивот занимает ~4,4 с на телефоне —
// пользователь ждёт эти секунды ради экономии байтов, которая нужна
// ТОЛЬКО радио-пути (LoRa). Интернет-релей везёт 44 и 341 байт
// одинаково. Политика: семантический конвейер бежит, только если
// сообщение пойдёт по радио.
//
// «Пойдёт по радио» = радио СКОНФИГУРИРОВАНО (mesh/ble/lan), а не
// «узел подключён прямо сейчас»: кадр из очереди уйдёт по радио, как
// только узел появится, а перекодировать вдогонку нельзя — один msgID
// обязан носить один и тот же внутренний payload обоими путями
// (инвариант дедупа; сообщение могло уже уехать релеем этим кадром).
// Широковещательное (без контакта) — радио-путь по построению: пивот
// всегда.
//
// Корпус диктовок при пропуске НЕ теряет тексты: запись диктовки
// создаётся до конвейера, пивоты добираются фермой на Маке (та же
// модель) — decision "skipped_no_radio" отличает эти записи от
// честных text-решений гейтов.
// ============================================================================

nonisolated enum SendPolicy {

    /// Причина текстового исхода при пропуске пивота — по ней UI и
    /// корпус отличают «политика» от «гейт» и «модель недоступна».
    static let skipReason = "быстрый путь — текстом, без задержки"

    /// Корпусная пометка пропуска (не «text»: гейты тут ни при чём,
    /// статистику решений искажать нельзя).
    static let skipDecision = "skipped_no_radio"

    /// Доктрина А1 (замер 09.08 на живом Release: модель 2,4–4,8 с,
    /// весь остальной путь 14,5 мс): узкий путь, ради которого стоит
    /// ждать модель, — ТОЛЬКО LoRa. Интернет-релей, BLE «рядом» и
    /// Wi-Fi Aware — быстрые: везут любой размер, обходят модель и
    /// кодек (E2E-шифр тот же). Прежние поводы («сосед рядом», «релей
    /// выключен») из уравнения убраны: сосед — быстрый путь, а
    /// выключенный релей сам по себе узости не создаёт.
    /// nearbyNow — параметр ЯВНЫЙ, чтобы замок держал именно это:
    /// сосед не смеет включать кодек.
    static func pivotWorthRunning(hasContact: Bool,
                                  loRaConfigured: Bool,
                                  nearbyNow: Bool = false) -> Bool {
        _ = nearbyNow   // быстрый путь: на решение не влияет
        return !hasContact || loRaConfigured
    }
}
