import Foundation

// ============================================================================
// «Начать заново» — полный сброс личности и всех данных (12.08).
//
// Зачем кнопка, если можно «снести приложение»: Keychain на iOS
// ПЕРЕЖИВАЕТ удаление приложения, поэтому переустановка (в т.ч. из
// TestFlight) возвращает ТУ ЖЕ личность → те же релейные ящики → друг
// досылает старое / релей переотдаёт, и прошлый чат воскресает.
// Полный сброс возможен только явным действием изнутри приложения.
//
// После сброса: новая личность (новый отпечаток, новые ящики — старые
// сообщения на релее недостижимы), пустые чаты, чистые надгробия/блоки.
// ============================================================================

@MainActor
enum AppReset {

    /// Стереть ВСЁ и сбросить личность. Необратимо.
    static func freshStart() {
        // 1. Контакты целиком: у каждого лог/шёпоты/рэтчет/позиции/
        //    очередь/релейный ящик пары (снимок ДО стирания — purge
        //    убирает из ContactStore по ходу)
        for contact in ContactStore.load() {
            ContactPurge.purge(contact)
        }
        // 2. Вся переписка целиком (демо-чат Софи + возможные остатки)
        HumanChatStore.purgeEverything()
        // 3. Надгробия, блоки, кольцо видённых msgID
        ContactAdmission.resetAll()
        UserDefaults.standard.removeObject(forKey: "seen_incoming_msg_ids")
        // 3б. Отказы знакомства (полевое 13.08: после сброса на «Моём
        // QR» висело «Отклонённых предложений: 1» от прошлой жизни)
        // + ожидающие приглашения двустороннего согласия (мега-2)
        IntroduceCenter.shared.clearAllDeclined()
        IntroduceCenter.shared.clearPendingInvites()
        // 3в. Сироты от давно удалённых контактов: счётчики пар и
        //     способности пиров (регресс билда 24: «ноль следов»
        //     значит ноль — попарной чистки мало)
        SeqStore.purgeAll()
        PeerCaps.purgeAll()
        // 3г. Гранты шеринга геопозиции (поле 14.08: после полного
        //     сброса висел значок геолокации — дисковый грант переживал
        //     сброс, и resumeOnAppOpen поднимал фоновую гео-сессию у
        //     «новой» личности). Стираем гранты и гасим сессию сразу.
        ShareGrantStore.save([])
        ShareSessionController.shared.syncWithGrants()
        // 3д. Реестр должников квитанций (в памяти — но сброс не
        //     обязан ждать перезапуска, чтобы стать честным)
        DeliveryManager.shared.clearReceiptDebtors()
        // 3е. Все следы Софи: истории и суммарии чатов, легаси-каталог
        //     Kaya (иначе миграция воскресит чаты), JSONL-трейс цикла,
        //     лог подмен дат; далее — ключ шифрования памяти
        //     (криптостирание). Публичный API линии Софи, тем же
        //     паттерном, что 3г у карты (заявка Софи-сессии 21.08,
        //     вариант «а» владельца; замок — SophieFreshStartCrossTests)
        SophiePurge.purgeAll()
        // 3ж. Пуши: unregister на релей (токен ещё жив), локальный
        //     токен и флаг вопроса забыты, уведомления сняты — новая
        //     личность не наследует пуш-канал старой (спека пушей §6)
        PushRegistrar.shared.purgeOnFreshStart()
        // 4. Сама личность (ключ, сид, ИМЯ и флаг вопроса имени) — новый ключ на следующем доступе
        Identity.reset()
        TransportDiary.note("[сброс] начать заново: личность и все данные "
                            + "стёрты, новая личность на перезапуске")
    }
}
