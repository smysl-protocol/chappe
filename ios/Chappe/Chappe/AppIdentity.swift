import Foundation

// ============================================================================
// Имена продукта — единственное место, где они записаны.
//
// Приложение: Chappe — в честь Клода Шаппа, изобретателя оптического
// телеграфа (1792). Ассистент: Софи — Sophie Françoise Chappe, сестра
// изобретателя.
//
// Правило: ни имя приложения, ни имя ассистента не пишутся в коде
// строкой — только через эти константы. Проверка: grep "Chappe"/"Софи"
// по *.swift должен находить только этот файл (плюс интерполяции).
// ============================================================================

enum AppIdentity {

    /// Имя приложения, как его видит пользователь.
    static let appName = "Chappe"

    /// Имя ассистента в интерфейсе (несклоняемое — русские падежи
    /// не требуют форм, в отличие от прежнего имени).
    static let assistantName = "Софи"

    /// Латинское написание имени ассистента.
    static let assistantNameLatin = "Sophie"

    /// Все написания, по которым срабатывает упоминание «@…»:
    /// русское и латинское, регистр не важен (сравнение в lowercased).
    /// Русский пользователь с русской раскладкой не должен промахнуться.
    static let assistantAliases = [assistantName.lowercased(),
                                   assistantNameLatin.lowercased()]
}
