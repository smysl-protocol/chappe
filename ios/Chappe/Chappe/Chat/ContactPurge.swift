import Foundation

// ============================================================================
// Полное стирание собеседника (удаление = ЧИСТЫЙ ЛИСТ, решение владельца
// 12.08).
//
// Было: удаление чистило основной лог и рэтчет, но оставляло шёпоты,
// отметку прочтения, позиции, недоставленную очередь и — главное —
// релейный ЯЩИК ПАРЫ. Повторное знакомство тем же ключом давало тот же
// ящик, и старые кадры из него переотдавались: прошлый чат «воскресал».
// Это (а) opsec-дыра (удалённая переписка возвращается) и (б) грязь в
// тестах первого контакта (каждый прогон загрязнён прошлым состоянием).
//
// Теперь ВСЕ сторы контакта чистятся ОДНИМ вызовом. Что НЕ трогаем
// осознанно:
//   • надгробие (ContactAdmission) — помнит имя→последний ключ для
//     тревоги при возврате с ДРУГИМ ключом (B2); это защита, не
//     переписка, и чистого листа не нарушает;
//   • блок — отдельное решение вызывающего (Удалить vs Удалить+блок).
// ============================================================================

@MainActor
enum ContactPurge {

    /// Стереть контакт целиком. Локальные сторы — синхронно; релейный
    /// ящик — best-effort async (без сети чистка ящика не произойдёт,
    /// но локальное стирание уже состоялось, и дедуп гасит повтор).
    static func purge(_ contact: Contact) {
        ContactStore.remove(id: contact.id)          // сам контакт
        HumanChatStore.purge(contactID: contact.id)  // лог + шёпоты + прочтение
        Outbox.removeAll(contactID: contact.id)      // недоставленная очередь
        RatchetStore.drop(contactID: contact.id)     // ключи/эпоха
        PeerPositionStore.shared.removePosition(for: contact.id)  // позиции
        RelayTransport.shared.purgeMailbox(for: contact)  // релейный ящик пары
        SeqStore.purge(contactID: contact.id)        // счётчик пары (рев B)
        PeerCaps.purge(contactID: contact.id)        // способности пира
        TransportDiary.note("[удаление] контакт \(contact.id) стёрт "
                            + "целиком (чистый лист)")
    }
}
